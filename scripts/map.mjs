// Regenerates the per-part dependency maps in book/index.md from chapter frontmatter.
import fs from 'node:fs'
import path from 'node:path'
import { BOOK_DIR, loadParts } from './chapters.mjs'

const INDEX = path.join(BOOK_DIR, 'index.md')
const START = '<!-- map:start -->'
const END = '<!-- map:end -->'

const parts = loadParts()
const byId = new Map(parts.flatMap((p) => p.chapters.map((c) => [c.id, c])))
const node = (id) => `c${id.replace('.', '_')}`
const label = (c) => `${c.id} ${c.title}`.replace(/"/g, "'")

// One flowchart per part: its chapters, plus prerequisites from other parts as grey nodes.
function partMap(p) {
  const own = new Set(p.chapters.map((c) => c.id))
  const external = new Set()
  const lines = ['```mermaid', 'flowchart TB']
  for (const c of p.chapters) lines.push(`  ${node(c.id)}["${label(c)}"]${c.tier === 'deeper' ? ':::deeper' : ''}`)
  for (const c of p.chapters) {
    for (const n of c.needs) {
      if (!own.has(n)) external.add(n)
      lines.push(`  ${node(n)} --> ${node(c.id)}`)
    }
  }
  for (const n of external) {
    const c = byId.get(n)
    lines.push(`  ${node(n)}["${c ? label(c) : n}"]:::external`)
  }
  lines.push('  classDef deeper stroke-dasharray: 5 5')
  lines.push('  classDef external fill:none,stroke:#999,color:#999')
  lines.push('```')
  return lines.join('\n')
}

const body = parts
  .filter((p) => p.chapters.length)
  .map((p) => `### Part ${p.number} · ${p.title}\n\n${partMap(p)}`)
  .join('\n\n')

const out = [
  START,
  '<!-- Generated by `npm run map` from chapter frontmatter. Don\'t edit by hand. -->',
  '',
  'Arrows point from a chapter to the chapters that need it. Dashed boxes are Deeper chapters; grey boxes are prerequisites from other parts.',
  '',
  body,
  END,
].join('\n')

const text = fs.readFileSync(INDEX, 'utf8')
const from = text.indexOf(START)
const to = text.indexOf(END)
if (from === -1 || to === -1) {
  console.error(`book/index.md is missing the ${START} / ${END} markers`)
  process.exit(1)
}
fs.writeFileSync(INDEX, text.slice(0, from) + out + text.slice(to + END.length))
console.log(`Updated book/index.md: ${byId.size} chapters in ${parts.length} parts`)
